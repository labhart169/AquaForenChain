"""SCADA/IoT event definitions for AquaForenChain.

The module intentionally uses plain dictionaries instead of a heavy domain
framework so that the prototype is easy to run on a normal laptop and easy to
inspect by reviewers.
"""
from __future__ import annotations

from dataclasses import dataclass, asdict
from datetime import datetime, timezone
from typing import Any, Dict, Optional


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


@dataclass
class SCADAEvent:
    event_id: str
    timestamp: str
    zone: str
    device_id: str
    device_type: str
    event_type: str
    value: Any
    unit: str
    severity: str
    operator_id: str
    source: str
    sequence: int
    nonce: str
    location: str
    description: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


EVENT_TYPES = [
    "TANK_LEVEL_READING",
    "PRESSURE_READING",
    "FLOW_READING",
    "CHLORINE_READING",
    "PUMP_STATE_CHANGE",
    "VALVE_STATE_CHANGE",
    "ALARM_RAISED",
    "OPERATOR_ACTION",
    "NETWORK_STATUS",
    "SECURITY_EVENT",
]

SEVERITY_ORDER = {"LOW": 1, "MEDIUM": 2, "HIGH": 3, "CRITICAL": 4}


def severity_for(event_type: str, value: Any) -> str:
    if event_type == "PRESSURE_READING":
        try:
            v = float(value)
        except Exception:
            return "MEDIUM"
        if v < 1.0 or v > 7.0:
            return "CRITICAL"
        if v < 1.8 or v > 5.8:
            return "HIGH"
        return "LOW"
    if event_type == "TANK_LEVEL_READING":
        v = float(value)
        if v < 15 or v > 95:
            return "CRITICAL"
        if v < 25 or v > 88:
            return "HIGH"
        return "LOW"
    if event_type in {"ALARM_RAISED", "SECURITY_EVENT"}:
        return "HIGH"
    if event_type == "OPERATOR_ACTION":
        return "MEDIUM"
    return "LOW"


def make_event(
    *,
    idx: int,
    zone: str,
    device_id: str,
    device_type: str,
    event_type: str,
    value: Any,
    unit: str = "",
    operator_id: str = "AUTO",
    source: str = "SCADA",
    location: str = "District-A",
    description: Optional[str] = None,
    timestamp: Optional[str] = None,
) -> Dict[str, Any]:
    event = SCADAEvent(
        event_id=f"EVT-{idx:06d}",
        timestamp=timestamp or utc_now_iso(),
        zone=zone,
        device_id=device_id,
        device_type=device_type,
        event_type=event_type,
        value=value,
        unit=unit,
        severity=severity_for(event_type, value),
        operator_id=operator_id,
        source=source,
        sequence=idx,
        nonce=f"N-{idx:06d}-{device_id}",
        location=location,
        description=description or f"{event_type} generated by {device_id}",
    )
    return event.to_dict()
