# ─── Hashing Throughput Benchmark ────────────────────────────────────────────

def benchmark_hashing_throughput(
    event_counts: List[int] = None,
    trials: int = 5,
    seed: int = 42,
    return_raw: bool = False,
):
    """Measure SHA-256 hashing throughput (events/second) at various scales."""
    if event_counts is None:
        event_counts = [100, 500, 1000, 2500, 5000, 10000]

    sim = SmartWaterSimulator(seed=seed)
    all_events = sim.generate_events(max(event_counts))
    rows = []
    raw_rows: List[Dict[str, Any]] = []
    for n in event_counts:
        subset = all_events[:n]
        trial_times = []
        for trial_idx in range(trials):
            t0 = time.perf_counter()
            hashes = [sha256_hex(e) for e in subset]
            elapsed = time.perf_counter() - t0
            trial_times.append(elapsed)
            raw_rows.append({
                "events": n,
                "trial_index": trial_idx + 1,
                "seed": seed,
                "elapsed_s": round(elapsed, 9),
                "throughput_events_per_sec": round(n / elapsed, 3),
            })
        mean_s = statistics.mean(trial_times)
        std_s = statistics.stdev(trial_times) if len(trial_times) > 1 else 0
        throughput = n / mean_s
        rows.append({
            "events": n,
            "trials": trials,
            "mean_hashing_s": round(mean_s, 6),
            "std_hashing_s": round(std_s, 6),
            "min_hashing_s": round(min(trial_times), 6),
            "max_hashing_s": round(max(trial_times), 6),
            "throughput_events_per_sec": round(throughput, 1),
            "throughput_hashes_per_sec": round(throughput, 1),
            "latency_per_event_us": round(mean_s / n * 1e6, 3),
        })
    return (rows, raw_rows) if return_raw else rows


# ─── Forensic Overhead Analysis ──────────────────────────────────────────────

def forensic_overhead_analysis(
    events: List[Dict[str, Any]],
    batch_sizes: List[int] = None,
) -> List[Dict[str, Any]]:
    """Measure total forensic processing overhead per event."""
    if batch_sizes is None:
        batch_sizes = [100, 500, 1000, 5000]
    rows = []
    for bs in batch_sizes:
        subset = events[:min(bs, len(events))]
        # Phase 1: Hashing
        t0 = time.perf_counter()
        hashes = [sha256_hex(e) for e in subset]
        t_hash = (time.perf_counter() - t0) * 1000
        # Phase 2: Merkle build
        t0 = time.perf_counter()
        tree = MerkleTree(hashes)
        t_merkle = (time.perf_counter() - t0) * 1000
        # Phase 3: Proof generation (all events)
        t0 = time.perf_counter()
        proofs = [tree.proof(i) for i in range(len(subset))]
        t_proofs = (time.perf_counter() - t0) * 1000
        # Phase 4: Batch verification (sample 10)
        sample = min(10, len(subset))
        t0 = time.perf_counter()
        for i in range(sample):
            verify_event_against_root(subset[i], proofs[i], tree.root)
        t_verify = (time.perf_counter() - t0) * 1000 / sample
        total_ms = t_hash + t_merkle + t_proofs
        rows.append({
            "batch_size": bs,
            "hashing_phase_ms": round(t_hash, 4),
            "merkle_build_ms": round(t_merkle, 4),
            "proof_gen_all_ms": round(t_proofs, 4),
            "verify_per_event_ms": round(t_verify, 4),
            "total_processing_ms": round(total_ms, 4),
            "overhead_per_event_ms": round(total_ms / bs, 6),
            "overhead_per_event_us": round(total_ms / bs * 1000, 3),
        })
    return rows


# ─── Sensitivity Analysis ────────────────────────────────────────────────────

def sensitivity_analysis(
    base_events: int = 5000,
    seeds: List[int] = None,
    batch_size: int = 5000,
) -> List[Dict[str, Any]]:
    """Test reproducibility across different random seeds."""
    if seeds is None:
        seeds = [0, 1, 7, 13, 21, 42, 99, 123, 256, 1337]
    rows = []
    for seed in seeds:
        sim = SmartWaterSimulator(seed=seed)
        events = sim.generate_events(base_events)
        hashes = [sha256_hex(e) for e in events]
        t0 = time.perf_counter()
        tree = MerkleTree(hashes)
        gen_ms = (time.perf_counter() - t0) * 1000
        ev_dist, sev_dist = summarize_events(events)
        proof = tree.proof(min(3, len(events) - 1))
        t0 = time.perf_counter()
        v = verify_event_against_root(events[3], proof, tree.root)
        v_ms = (time.perf_counter() - t0) * 1000
        rows.append({
            "seed": seed,
            "events": base_events,
            "merkle_root_prefix": tree.root[:16] + "...",
            "merkle_depth": tree.depth,
            "merkle_gen_ms": round(gen_ms, 4),
            "verify_ms": round(v_ms, 4),
            "verification_valid": v["valid"],
            "critical_events": sev_dist.get("CRITICAL", 0),
            "high_events": sev_dist.get("HIGH", 0),
            "security_events": ev_dist.get("SECURITY_EVENT", 0),
            "alarm_events": ev_dist.get("ALARM_RAISED", 0),
            "twin_state": sim.snapshot()["state"],
        })
    return rows


