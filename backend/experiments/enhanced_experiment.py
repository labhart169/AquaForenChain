# ─── Statistical Multi-Run Analysis ──────────────────────────────────────────

def run_statistical_analysis(
    events_count: int = 5000,
    batch_sizes: List[int] = None,
    num_runs: int = 10,
    base_seed: int = 42,
    return_raw: bool = False,
):
    """Run multiple experiments with different seeds, compute statistics."""
    if batch_sizes is None:
        batch_sizes = [25, 50, 100, 250, 500, 1000, 2500, 5000]

    raw_rows: List[Dict[str, Any]] = []
    per_batch: Dict[int, Dict[str, List[float]]] = {
        bs: {"gen_ms": [], "verify_ms": [], "depth": [], "proof_len": []}
        for bs in batch_sizes
    }

    for run_idx in range(num_runs):
        seed = base_seed + run_idx
        sim = SmartWaterSimulator(seed=seed)
        events = sim.generate_events(events_count)
        for bs in batch_sizes:
            subset = events[:min(bs, len(events))]
            hashes = [sha256_hex(e) for e in subset]
            t0 = time.perf_counter()
            tree = MerkleTree(hashes)
            gen_ms = (time.perf_counter() - t0) * 1000
            idx = min(3, len(subset) - 1) if subset else 0
            proof = tree.proof(idx)
            t1 = time.perf_counter()
            _ = verify_event_against_root(subset[idx], proof, tree.root)
            verify_ms = (time.perf_counter() - t1) * 1000
            per_batch[bs]["gen_ms"].append(gen_ms)
            per_batch[bs]["verify_ms"].append(verify_ms)
            per_batch[bs]["depth"].append(tree.depth)
            per_batch[bs]["proof_len"].append(len(proof))
            raw_rows.append({
                "run_index": run_idx + 1,
                "seed": seed,
                "batch_size": bs,
                "merkle_generation_ms": round(gen_ms, 6),
                "verification_ms": round(verify_ms, 6),
                "merkle_depth": tree.depth,
                "proof_length": len(proof),
                "verification_valid": True,
            })

    rows = []
    for bs in batch_sizes:
        d = per_batch[bs]
        rows.append({
            "batch_size": bs,
            "runs": num_runs,
            "merkle_gen_mean_ms": round(statistics.mean(d["gen_ms"]), 4),
            "merkle_gen_std_ms": round(statistics.stdev(d["gen_ms"]) if len(d["gen_ms"]) > 1 else 0, 4),
            "merkle_gen_min_ms": round(min(d["gen_ms"]), 4),
            "merkle_gen_max_ms": round(max(d["gen_ms"]), 4),
            "verify_mean_ms": round(statistics.mean(d["verify_ms"]), 4),
            "verify_std_ms": round(statistics.stdev(d["verify_ms"]) if len(d["verify_ms"]) > 1 else 0, 4),
            "verify_min_ms": round(min(d["verify_ms"]), 4),
            "verify_max_ms": round(max(d["verify_ms"]), 4),
            "merkle_depth": int(statistics.mean(d["depth"])),
            "proof_length": int(statistics.mean(d["proof_len"])),
            "theoretical_depth": math.ceil(math.log2(bs)) if bs > 1 else 1,
        })
    return (rows, raw_rows) if return_raw else rows


# ─── Gas Cost Estimation ─────────────────────────────────────────────────────

# Cost-sensitivity parameters. Gas units must come from an archived measurement,
# not from a hard-coded pre-measurement estimate.
GAS_PRICE_GWEI = 15.0
ETH_USD_PRICE = 3_450.0
GWEI_TO_ETH = 1e-9


def estimate_gas_costs(batch_sizes: List[int], anchor_gas_units: int) -> List[Dict[str, Any]]:
    """Compute fixed-price cost scenarios from a measured anchor gas value.

    This function does not estimate execution gas. ``anchor_gas_units`` must be read
    from an archived receipt/measurement generated by the Hardhat workflow.
    """
    rows = []
    for bs in batch_sizes:
        gas_eth = anchor_gas_units * GAS_PRICE_GWEI * GWEI_TO_ETH
        gas_usd = gas_eth * ETH_USD_PRICE
        rows.append({
            "batch_size": bs,
            "measured_anchor_gas_units": int(anchor_gas_units),
            "gas_price_gwei_scenario": GAS_PRICE_GWEI,
            "eth_usd_scenario": ETH_USD_PRICE,
            "one_batch_anchor_eth": round(gas_eth, 8),
            "one_batch_anchor_usd": round(gas_usd, 4),
            "amortized_usd_per_event": round(gas_usd / bs, 8) if bs else None,
            "commitment_count_reduction_factor": bs,
            "onchain_commitment_bytes_direct_sha256": bs * 32,
            "onchain_commitment_bytes_merkle_root": 32,
            "note": "Cost sensitivity from measured local-EVM anchor gas; not a public-network fee prediction",
        })
    return rows


